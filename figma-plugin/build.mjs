// Builds figma-plugin/code.js: the token file inlined ahead of the plugin source, so Figma
// reads the same values as the site. Run with `npm run figma:plugin` after any token change.
import { readFileSync, writeFileSync } from 'node:fs';
const tokens = readFileSync(new URL('../tokens/tokens.json', import.meta.url), 'utf8');
const src = readFileSync(new URL('./src/plugin.js', import.meta.url), 'utf8');
const header = '// GENERATED by figma-plugin/build.mjs from tokens/tokens.json and src/plugin.js. Do not edit by hand.\n';
writeFileSync(new URL('./code.js', import.meta.url), `${header}const TOKENS = ${tokens.trim()};\n\n${src}`);
console.log('figma-plugin/code.js written');
